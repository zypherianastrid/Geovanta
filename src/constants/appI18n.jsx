const translateToast = (msg, lang) => {
  if (lang !== 'en' || !msg) return msg;
  if (TOAST_EN[msg]) return TOAST_EN[msg];
  for (const [re, rep] of TOAST_PATTERNS) {
    if (re.test(msg)) return msg.replace(re, rep);
  }
  return msg;
};

